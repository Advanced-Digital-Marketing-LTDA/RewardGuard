from __future__ import annotations

import csv
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parents[1] / "scripts"
sys.path.insert(0, str(SCRIPT_DIR))

import rewardguard_scan as scanner  # noqa: E402


def git_init(root: Path) -> None:
    subprocess.run(["git", "init", "-q", str(root)], check=True)


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


class RewardGuardScanTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)
        self.judge_temp = tempfile.TemporaryDirectory()
        git_init(self.root)

    def tearDown(self) -> None:
        self.judge_temp.cleanup()
        self.temp.cleanup()

    def fake_judge(self) -> Path:
        path = Path(self.judge_temp.name) / "fake_judge.py"
        write(path, '''
import json, sys
request = json.load(sys.stdin)
findings = []
if request["mode"] == "review":
    for unit in request["units"]:
        for offset, line in enumerate(unit["source"].splitlines()):
            if line.startswith("BUG ="):
                findings.append({
                    "severity": "high",
                    "category": "correctness",
                    "confidence": 0.95,
                    "title": "Incorrect value, check",
                    "description": "The marked value is known to be incorrect.",
                    "file": unit["file"],
                    "line_start": unit["line_start"] + offset,
                    "line_end": unit["line_start"] + offset,
                    "evidence": line,
                    "recommendation": "Replace the value.",
                    "related_files": [],
                })
print(json.dumps({
    "reviewed_unit_ids": request["expected_unit_ids"],
    "summary": "Reviewed the supplied source units.",
    "findings": findings,
}))
''')
        return path

    def test_manifest_excludes_data_generated_ignored_and_symlink_files(self) -> None:
        write(self.root / "src/app.py", "value = 1\n")
        write(self.root / "records.csv", "id,value\n1,2\n")
        write(self.root / "store.sqlite3", "not a database")
        write(self.root / "fixtures/rows.json", '[{"id": 1}]\n')
        write(self.root / "src/message.generated.py", "value = 9\n")
        write(self.root / "generated/auto.py", "value = 2\n")
        write(self.root / "src/generated.py", "# Generated by tool\nvalue = 3\n")
        write(self.root / ".gitignore", "ignored.py\n")
        write(self.root / "ignored.py", "value = 4\n")
        (self.root / "src/link.py").symlink_to(self.root / "src/app.py")

        entries, excluded = scanner.collect_manifest(self.root, self.root / "findings.csv", 100_000)
        included = {entry.path for entry in entries}
        reasons = dict(excluded)

        self.assertIn("src/app.py", included)
        self.assertNotIn("records.csv", included)
        self.assertNotIn("store.sqlite3", included)
        self.assertNotIn("fixtures/rows.json", included)
        self.assertNotIn("ignored.py", included)
        self.assertEqual(reasons["generated/auto.py"], "generated, dependency, or cache directory")
        self.assertEqual(reasons["src/generated.py"], "generated-file marker")
        self.assertEqual(reasons["src/message.generated.py"], "generated filename pattern")
        self.assertEqual(reasons["src/link.py"], "symlink")

    def test_plan_does_not_invoke_judge(self) -> None:
        write(self.root / "src/app.py", "value = 1\n")
        output = self.root / "findings.csv"
        status = scanner.main([
            "--repo-root", str(self.root), "--output", str(output), "--plan",
            "--judge-command", "/bin/false",
        ])
        self.assertEqual(status, 0)
        self.assertFalse(output.exists())

    def test_review_synthesis_and_csv_quoting(self) -> None:
        source = 'safe = 1\nBUG = "needs, quote"\n'
        write(self.root / "src/app.py", source)
        judge = self.fake_judge()
        output = self.root / "findings.csv"

        status = scanner.main([
            "--repo-root", str(self.root), "--output", str(output),
            "--judge-command", f"{sys.executable} {judge}",
        ])

        self.assertEqual(status, 0)
        with output.open(encoding="utf-8", newline="") as stream:
            rows = list(csv.DictReader(stream))
        self.assertEqual(len(rows), 1)
        self.assertEqual(rows[0]["evidence"], 'BUG = "needs, quote"')
        self.assertEqual(rows[0]["file"], "src/app.py")
        self.assertTrue(rows[0]["finding_id"])

    def test_zero_findings_writes_header_only_csv(self) -> None:
        write(self.root / "src/app.py", "safe = 1\n")
        judge = self.fake_judge()
        output = self.root / "findings.csv"
        status = scanner.main([
            "--repo-root", str(self.root), "--output", str(output),
            "--judge-command", f"{sys.executable} {judge}",
        ])
        self.assertEqual(status, 0)
        with output.open(encoding="utf-8", newline="") as stream:
            rows = list(csv.DictReader(stream))
        self.assertEqual(rows, [])
        with output.open(encoding="utf-8", newline="") as stream:
            self.assertEqual(next(csv.reader(stream)), list(scanner.CSV_COLUMNS))

    def test_judge_failure_preserves_existing_output(self) -> None:
        write(self.root / "src/app.py", "safe = 1\n")
        output = self.root / "findings.csv"
        output.write_text("previous result\n", encoding="utf-8")

        status = scanner.main([
            "--repo-root", str(self.root), "--output", str(output),
            "--judge-command", "/bin/false",
        ])

        self.assertEqual(status, 1)
        self.assertEqual(output.read_text(encoding="utf-8"), "previous result\n")

    def test_line_chunks_cover_every_line_without_overlap(self) -> None:
        entry = scanner._metadata("src/large.py", "one = 1\ntwo = 2\nthree = 3\n")
        units = scanner.build_units([entry], 11)
        covered = []
        for unit in units:
            covered.extend(range(unit.line_start, unit.line_end + 1))
        self.assertEqual(covered, [1, 2, 3])
        self.assertEqual("".join(unit.source for unit in units), entry.text)

    def test_invalid_evidence_is_rejected(self) -> None:
        entry = scanner._metadata("src/app.py", "value = 1\n")
        finding = {
            "severity": "high", "category": "correctness", "confidence": 0.9,
            "title": "Bad value", "description": "Example", "file": "src/app.py",
            "line_start": 1, "line_end": 1, "evidence": "value = 2",
            "recommendation": "Fix it.", "related_files": [],
        }
        with self.assertRaises(scanner.ScanError):
            scanner._validate_findings([finding], [entry], {"src/app.py": [(1, 1)]}, "review-1", "")

    def test_non_object_judge_response_is_rejected(self) -> None:
        with self.assertRaises(scanner.ScanError):
            scanner._validate_response([], [], 4096)


if __name__ == "__main__":
    unittest.main()
